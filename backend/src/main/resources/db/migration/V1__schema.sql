-- FITTRACK schema

CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(80)  NOT NULL,
    email            VARCHAR(160) NOT NULL UNIQUE,
    password_hash    VARCHAR(100) NOT NULL,
    avatar           TEXT,
    birth_date       DATE,
    height_cm        INTEGER,
    weight_kg        NUMERIC(5, 1),
    goal             VARCHAR(30),
    experience_level VARCHAR(20)  NOT NULL DEFAULT 'BEGINNER',
    weekly_goal      INTEGER      NOT NULL DEFAULT 4,
    default_rest_seconds INTEGER  NOT NULL DEFAULT 90,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token      VARCHAR(80)  NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used       BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE muscle_groups (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug     VARCHAR(40) NOT NULL UNIQUE,
    name     VARCHAR(60) NOT NULL,
    region   VARCHAR(10) NOT NULL,
    position INTEGER     NOT NULL
);

CREATE TABLE exercises (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(80)  NOT NULL UNIQUE,
    name             VARCHAR(120) NOT NULL,
    primary_muscle_id BIGINT      NOT NULL REFERENCES muscle_groups (id),
    equipment        VARCHAR(20)  NOT NULL,
    difficulty       VARCHAR(20)  NOT NULL,
    movement         VARCHAR(30)  NOT NULL,
    description      TEXT         NOT NULL,
    instructions     TEXT         NOT NULL
);

CREATE INDEX idx_exercises_primary_muscle ON exercises (primary_muscle_id);

CREATE TABLE exercise_secondary_muscles (
    exercise_id     BIGINT NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    muscle_group_id BIGINT NOT NULL REFERENCES muscle_groups (id),
    PRIMARY KEY (exercise_id, muscle_group_id)
);

CREATE TABLE user_favorite_exercises (
    user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, exercise_id)
);

CREATE TABLE workouts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    letter      VARCHAR(2),
    position    INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_workouts_user ON workouts (user_id);

CREATE TABLE workout_exercises (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id   BIGINT  NOT NULL REFERENCES workouts (id) ON DELETE CASCADE,
    exercise_id  BIGINT  NOT NULL REFERENCES exercises (id),
    position     INTEGER NOT NULL,
    sets         INTEGER NOT NULL,
    reps         INTEGER NOT NULL,
    rest_seconds INTEGER NOT NULL,
    notes        VARCHAR(300)
);

CREATE INDEX idx_workout_exercises_workout ON workout_exercises (workout_id);

CREATE TABLE workout_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        VARCHAR(64)  NOT NULL UNIQUE,
    user_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    workout_id       BIGINT       REFERENCES workouts (id) ON DELETE SET NULL,
    workout_name     VARCHAR(100) NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    started_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at      TIMESTAMP WITH TIME ZONE,
    duration_seconds INTEGER      NOT NULL DEFAULT 0,
    total_volume     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_reps       INTEGER      NOT NULL DEFAULT 0,
    completed_sets   INTEGER      NOT NULL DEFAULT 0,
    notes            VARCHAR(500)
);

CREATE INDEX idx_sessions_user_status ON workout_sessions (user_id, status, finished_at);

CREATE TABLE exercise_sets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     BIGINT  NOT NULL REFERENCES workout_sessions (id) ON DELETE CASCADE,
    exercise_id    BIGINT  NOT NULL REFERENCES exercises (id),
    exercise_order INTEGER NOT NULL,
    set_number     INTEGER NOT NULL,
    planned_reps   INTEGER NOT NULL,
    rest_seconds   INTEGER NOT NULL,
    weight_kg      NUMERIC(6, 2) NOT NULL DEFAULT 0,
    reps           INTEGER NOT NULL DEFAULT 0,
    completed      BOOLEAN NOT NULL DEFAULT FALSE,
    skipped        BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_sets_session ON exercise_sets (session_id);
CREATE INDEX idx_sets_exercise ON exercise_sets (exercise_id);

CREATE TABLE personal_records (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    exercise_id BIGINT        NOT NULL REFERENCES exercises (id),
    type        VARCHAR(20)   NOT NULL,
    record_value NUMERIC(10, 2) NOT NULL,
    weight_kg   NUMERIC(6, 2) NOT NULL,
    reps        INTEGER       NOT NULL,
    session_id  BIGINT        REFERENCES workout_sessions (id) ON DELETE SET NULL,
    achieved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_record UNIQUE (user_id, exercise_id, type)
);
